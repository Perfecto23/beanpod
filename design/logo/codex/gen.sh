#!/bin/zsh
# 让 Codex 画豆仓的图标：小豆戴着耳机，正在埋头把听到的话写下来。三个构图各出一张。
cd "$(dirname "$0")"
gen() {
  local name=$1; local prompt=$2
  [ -f "$name.png" ] && return
  local t0=$(date +%s)
  codex exec --skip-git-repo-check --ephemeral -c 'model_reasoning_effort="low"' -C "$PWD" -s workspace-write \
    "当前目录有两张角色参考图 ref_concept.png 和 ref_front.png，是同一个角色「小豆」：一只圆滚滚的珍珠白小仓鼠，腮帮子鼓鼓的，粉色的圆耳朵内侧，黑亮的豆豆眼，粉色小鼻子，脖子上挂着一副白色头戴耳机。请先看这两张图，然后使用内置的 image_gen 工具（把参考图一起传进去，保持角色长相一致）生成一张 1024×1024 的方形图片：$prompt 生成后把最终图片复制到当前目录，命名为 $name.png，然后只回复文件名。" < /dev/null > "$name.log" 2>&1
  echo "$name $(( $(date +%s) - t0 ))s $([ -f $name.png ] && echo ok || echo FAIL)"
}
C="这是一个 macOS App 的图标主画面。高品质 3D 渲染，高端潮玩手办的质感，绒毛柔软细腻，柔和的棚拍主光加一点暖色轮廓光。背景是满幅的深石墨黑（接近 #141414），不要画圆角方块、不要边框，小豆身后有一团柔和的琥珀色暖光晕。角色半身特写、居中、占画面七成左右，轮廓清晰，缩到很小也认得出来。全画面只用三种颜色：珍珠白、石墨黑、琥珀橙（#FFB23D），耳机外圈有一圈琥珀色的发光灯环。绝对不要蓝色、紫色、青色。无文字、无字母、无 Logo、无水印。"
gen write_a "小豆把耳机戴在头上（罩住两只耳朵的位置），微微低头，神情专注，一只小爪子握着一支短短的琥珀色铅笔，正在面前一本摊开的小本子上认真写字，另一只小爪子按着本子。本子在画面下方，只露出上半部分，纸面上是几行抽象的短横线（不是真实文字）。$C" &
gen write_b "小豆歪着头侧耳倾听，一只小爪子抬起来按在耳机的一只耳罩上，另一只小爪子握着一支琥珀色的笔，笔尖悬在一张小便签纸上方正要落笔，眼睛向上看、像在边听边想怎么记。$C" &
gen write_c "小豆戴着耳机，正面朝向镜头，两只小爪子一起握着一支大大的琥珀色铅笔（铅笔相对它的身体显得很大，斜着横在胸前），铅笔尖刚在面前画出一小段琥珀色的声波线条，声波线条的末端渐渐变成几行整齐的短横线（象征声音被写成了文字）。表情认真又有点得意。$C" &
wait
