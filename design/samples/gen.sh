#!/bin/zsh
# 豆仓内置的示例素材：两个示例主播（AI 生成的虚构人物）+ 三张包装风格预览图。
# 参考图是 design/ui 里设计稿的裁切（ref/），用 Codex 的 image_gen 重出高清版。
cd "$(dirname "$0")"
gen() {
  local name=$1; local ref=$2; local prompt=$3
  [ -f "$name.png" ] && return
  local t0=$(date +%s)
  codex exec --skip-git-repo-check --ephemeral -c 'model_reasoning_effort="low"' -C "$PWD" -s workspace-write \
    "请使用内置的 image_gen 工具生成一张图片。附带的图片只是参考（来自一张界面设计稿的低清裁切），按它的人物气质、服装和构图重新画一张高清的：$prompt 生成后把最终图片复制到当前目录，命名为 $name.png，然后只回复文件名。" -i "ref/$ref" < /dev/null > "$name.log" 2>&1
  echo "$name $(( $(date +%s) - t0 ))s $([ -f $name.png ] && echo ok || echo FAIL)"
}
P="写实摄影，像专业棚拍的人像参考照：人物是虚构的、不对应任何真实的人；正脸看镜头、五官清晰、自然微笑；光线柔和均匀、没有遮挡；皮肤自然有真实毛孔，不磨皮；画面里不要任何文字、水印或 Logo。"
gen sample_office office.jpg "竖构图（1024×1536）。一位三十岁左右的东亚女性，深棕色长卷发，戴小珍珠耳钉，穿浅驼色西装外套和米白色针织内搭，半身（头顶到腰），人在画面正中，背景是干净的浅灰色无缝背景纸。$P" &
gen sample_home home.jpg "横构图（1536×1024）。一位二十多岁的东亚女性，深色长发自然披肩，穿奶白色粗针织毛衣，半身，人在画面正中偏下，背景是温暖明亮的居家客厅（浅色墙、一盆绿植、暖光台灯），背景轻微虚化。$P" &
S="横构图（1536×1024），这是一款视频剪辑软件里「包装风格」的预览缩略图，像一帧口播短视频的截图：一位二十多岁的东亚男性（虚构人物），短黑发、深灰色圆领毛衣，半身，看镜头微笑。画面底部有一条很细的播放进度条（左边一小段玫瑰红 #F43F5E，其余白色半透明），左下角一个白色小三角播放图标，右下角白色小字 03:24。所有中文字清晰、没有乱码。"
gen style_premium premium.jpg "$S 风格「高级 · 网感」：温暖的书房背景（绿植、台灯虚化），画面四角有白色细线取景框角标，人物在画面中间偏右。" &
gen style_restrained restrained.jpg "$S 风格「高级 · 克制」：干净的浅灰色背景，人物在画面右侧，左上方是两行黑色中文标题「一个 / 高效思考的方法」，字体像苹方中粗，标题下一条很短的玫瑰红细线，留白多、克制。" &
gen style_variety variety.jpg "$S 风格「综艺花字」：人物是带白色描边的抠像贴纸效果、在画面左侧、开心大笑，右侧是倾斜的综艺花字「这也太 / 好用了！」（黑色和玫瑰红、粗描边），旁边几道玫瑰红的感叹线条，热闹但不杂乱，背景浅灰。" &
wait
