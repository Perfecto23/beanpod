#!/bin/zsh
# 让 Codex 出「刘海动画」的分镜设计稿：开始录音时小豆从刘海里探出头，录完像拍立得/热敏打印一样从刘海「滋」地吐出一截胶片，再被剪下来。
cd "$(dirname "$0")"
name=ui_notch_anim
[ -f "$name.png" ] && exit 0
P="当前目录有 ui_notch.png（豆仓现在的刘海快捷面板设计：MacBook 刘海往下展开的纯黑圆角面板）和 ref_mascot2.png（吉祥物小豆：珍珠白圆滚滚小仓鼠，戴白色耳机）。请先看这两张图，然后使用内置的 image_gen 工具（把它们一起传入）生成一张 16:9 横向的高保真动效分镜稿，浅暖灰背景，一排 5 格（每格是 MacBook 屏幕顶部正中刘海的特写，正视图，桌面是柔和暖色壁纸，格子下方有编号和一行简体中文说明）：
① 「点开始录音」：刘海是普通的黑色胶囊，没有展开。
② 「小豆探头」：刘海下沿像一个洞口，小豆只露出上半个脑袋，两只圆耳朵和一双亮晶晶的眼睛从刘海下沿冒出来，耳机先露出来，带一点向下弹的动势线。
③ 「开始听」：小豆整个头探出来，趴在刘海下沿，两只小爪子扒着边，左边耳朵位置一个玫瑰红小圆点和计时「00:03」，右边一小段跳动的玫瑰红声波；小豆表情专注在听。
④ 「录完，滋——打印」：小豆缩回去，刘海下沿像打印机出纸口，往下吐出一条竖向的胶片（米白色热敏纸质感，两侧有齿孔，上面印着一段玫瑰红声波图形、标题「组会纪要 · 12:48」和日期），纸条边缘有很细的速度线，旁边一个小小的拟声字「滋——」。
⑤ 「咔嚓，剪下」：一把小剪刀图标在刘海下沿把胶片剪断，剪下的胶片带一点旋转往下飘落，旁边一个小气泡「已存进豆仓」。
整体克制、高级、可爱但不幼稚，像苹果设计奖级别的 macOS 小工具动效。强调色只用玫瑰红 #F43F5E，绝对不要蓝色、紫色、琥珀橙。所有文字是简体中文，像苹方，清晰可读、没有乱码。生成后把最终图片复制到当前目录，命名为 $name.png，然后只回复文件名。"
t0=$(date +%s)
codex exec --skip-git-repo-check --ephemeral -c 'model_reasoning_effort="low"' -C "$PWD" -s workspace-write "$P" < /dev/null > "$name.log" 2>&1
echo "$name $(( $(date +%s) - t0 ))s $([ -f $name.png ] && echo ok || echo FAIL)"
