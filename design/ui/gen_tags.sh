#!/bin/zsh
# 标签：给录音和素材自己打标签、按标签筛选、侧栏看所有标签。
cd "$(dirname "$0")"
gen() {
  local name=$1; local prompt=$2
  [ -f "$name.png" ] && return
  local t0=$(date +%s)
  codex exec --skip-git-repo-check --ephemeral -c 'model_reasoning_effort="low"' -C "$PWD" -s workspace-write \
    "请使用内置的 image_gen 工具生成一张高保真 UI 设计稿（像设计师在 Figma 里做的最终稿截图，正视图、不要透视、纯浅灰背景上只放这一个窗口）：$prompt 生成后把最终图片复制到当前目录，命名为 $name.png，然后只回复文件名。" < /dev/null > "$name.log" 2>&1
  echo "$name $(( $(date +%s) - t0 ))s $([ -f $name.png ] && echo ok || echo FAIL)"
}
S="这是 macOS 桌面应用「豆仓」（把录音和视频素材转成文字、整理成纪要）。设计语言：苹果 macOS 最新系统的风格加乔纳森·艾维式的克制——圆角卡片、细分隔线、说明是小号灰字、对齐严谨、留白舒服。配色严格限定：暖灰纸色背景（#FAF9F7）、卡片纯白、深暖灰文字（#1C1917）、唯一强调色玫瑰红（#F43F5E，用在主按钮、选中状态）；标签胶囊用很浅的暖灰底+深灰字，选中的标签是浅玫瑰红底+玫瑰红字；绝对不要蓝色、紫色、青色、彩虹色。界面文字全部是简体中文，字体像苹方，清晰可读、没有乱码。"
gen ui_tags_list "【录音列表 + 按标签筛选】一个 macOS 窗口宽约 1200：左边窄侧栏（小仓鼠头像「豆仓」、开始录音按钮、总览/录音/素材/知识库，下面一个分组标题「标签」，列出几个标签行，每行左边一个小「#」、名字、右边灰色数字：「#客户 12」「#选题 8」「#周会 5」「#灵感 4」，其中「#客户」选中为浅玫瑰红底），中间是录音列表：顶部标题「#客户」和小字「12 条」，一行筛选胶囊「全部 / 星标 / 有待办」，下面几行录音卡片（标题、时间 · 时长 · 场合、右边两个小标签胶囊，其中「客户」胶囊是玫瑰红强调）；右边详情的标题下方有一行标签胶囊「# 客户」「# 预算」「# 周四跟进」，每个胶囊悬停时右侧出现小「×」，最后是一个虚线小胶囊「＋ 标签」。$S" &
gen ui_tags_edit "【给一条录音加标签的弹出小窗】一个从「＋ 标签」按钮弹出的小浮层（popover），宽约 320：顶部一个输入框，里面正在输入「预」，下面是建议列表：「预算」（右侧灰字「6 条」）、「预约回访」（「2 条」），最下面一行「新建标签「预」」；输入框上方一行小字「这条录音的标签」，已经有的标签以胶囊显示「客户 ×」「周四跟进 ×」；底部小灰字「回车添加，AI 整理出的标签也可以在这里删改。」。浮层下面隐约露出录音详情页的一部分。$S" &
wait
