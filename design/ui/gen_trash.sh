#!/bin/zsh
# 最近删除：本机删除的录音先放 7 天，可以恢复。
cd "$(dirname "$0")"
gen() {
  local name=$1; local prompt=$2
  [ -f "$name.png" ] && return
  local t0=$(date +%s)
  codex exec --skip-git-repo-check --ephemeral -c 'model_reasoning_effort="low"' -C "$PWD" -s workspace-write \
    "请使用内置的 image_gen 工具生成一张高保真 UI 设计稿（像设计师在 Figma 里做的最终稿截图，正视图、不要透视、纯浅灰背景上只放这一个窗口）：$prompt 生成后把最终图片复制到当前目录，命名为 $name.png，然后只回复文件名。" < /dev/null > "$name.log" 2>&1
  echo "$name $(( $(date +%s) - t0 ))s $([ -f $name.png ] && echo ok || echo FAIL)"
}
S="这是 macOS 桌面应用「豆仓」（把录音和视频素材转成文字、整理成纪要）。浅色模式。设计语言：苹果 macOS 最新系统的风格加乔纳森·艾维式的克制——圆角卡片、细分隔线、说明是小号灰字、对齐严谨、留白舒服。配色严格限定：暖灰纸色背景（#FAF9F7）、卡片纯白、深暖灰文字（#1C1917）、唯一强调色玫瑰红（#F43F5E，用在主按钮、选中状态）；绝对不要蓝色、紫色、青色、彩虹色。界面文字全部是简体中文，字体像苹方，清晰可读、没有乱码。"
gen ui_trash "【「最近删除」页面】一个 macOS 窗口宽约 1180：左边窄侧栏（小仓鼠头像「豆仓」、开始录音按钮、总览/录音/素材/知识库，项目、标签分组，侧栏最下方在设备卡上面有一行「最近删除 3」（垃圾桶图标，选中为浅玫瑰红底），底部设备卡「soundcore Work · 已连接」和一个齿轮按钮）。右边主区域：大标题「最近删除」，标题下一行灰色小字「删掉的录音在这里放 7 天，到期自动彻底删除。文字稿、纪要、标签都在，恢复后原样回来。」右上角一个次要按钮「全部清空」（文字是玫瑰红）。下面是一张白色卡片列表，每行：左边小图标（录音是波形图标、素材是视频缩略图），标题「周会确定新品发布时间与退款率排查」，灰色小字「录音 · 44 秒 · 11月16日删除」，右边一个小标签胶囊「还剩 6 天」（剩 1 天的那行胶囊是淡琥珀色「明天删除」），再右边两个按钮「恢复」（次要按钮）和一个小「⋯」。共 3 行，其中一行是素材「为什么要搞死黄仁勋？ · 小红书 · 16 分钟」。另外在窗口顶部居中画一个浮动的毛玻璃胶囊提示条：「已移到最近删除」+ 右侧玫瑰红文字按钮「撤销」。$S"
