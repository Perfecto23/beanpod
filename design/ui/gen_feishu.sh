#!/bin/zsh
# 从飞书妙记同步：手机官方 App 同步走的录音，从飞书拉回豆仓。
cd "$(dirname "$0")"
gen() {
  local name=$1; local prompt=$2
  [ -f "$name.png" ] && return
  local t0=$(date +%s)
  codex exec --skip-git-repo-check --ephemeral -c 'model_reasoning_effort="low"' -C "$PWD" -s workspace-write \
    "请使用内置的 image_gen 工具生成一张高保真 UI 设计稿（像设计师在 Figma 里做的最终稿截图，正视图、不要透视、纯浅灰背景上只放这一个窗口）：$prompt 生成后把最终图片复制到当前目录，命名为 $name.png，然后只回复文件名。" < /dev/null > "$name.log" 2>&1
  echo "$name $(( $(date +%s) - t0 ))s $([ -f $name.png ] && echo ok || echo FAIL)"
}
S="这是 macOS 桌面应用「豆仓」（把录音转成文字、整理成纪要）。浅色模式。设计语言：苹果 macOS 最新系统的风格加乔纳森·艾维式的克制——圆角卡片、细分隔线、说明是小号灰字、对齐严谨、留白舒服。配色严格限定：暖灰纸色背景（#FAF9F7）、卡片纯白、深暖灰文字（#1C1917）、唯一强调色玫瑰红（#F43F5E，用在主按钮、选中状态）；绝对不要蓝色、紫色、青色、彩虹色。界面文字全部是简体中文，字体像苹方，清晰可读、没有乱码。"
gen ui_feishu "【从飞书妙记同步】一个 macOS 窗口宽约 1260，左边窄侧栏（小仓鼠头像「豆仓」、玫瑰红「开始录音」按钮、总览/录音 21/素材/语音输入/知识库，底部设备卡「soundcore Work · 已连接」和齿轮按钮）。主区域是「设备」页：上半部是录音豆卡片（耳机图标、soundcore Work、电量 90%、已连接），下面新增一张白色圆角卡片「飞书妙记」：左上是一个暖灰圆角方块里的「飞」字小图标，标题「飞书妙记」，副标题灰字「手机上的录音豆 App 把录音同步到飞书后，录音豆上就没有了。豆仓从飞书把它们拉回来。」右上角状态「已连接 · 你的飞书账号」+ 一个小开关「自动同步」（开，玫瑰红）。卡片里是一张列表，表头小灰字「最近的妙记 · 上次检查 2 分钟前」，每行：左边勾选框，标题（如「下午的产品讨论」「11月16日 12:43 录音」），灰字「11月16日 12:43 · 44 分钟」，右边状态：已经拉回来的写灰色「已在豆仓」带对勾，没拉的行勾选框是勾上的、右边写「新的」小胶囊（浅玫瑰红底玫瑰红字）。列表下面一行按钮：主按钮玫瑰红「拉回 2 条」，次要按钮「现在检查」，再右边灰字链接「不想要的可以取消勾选，之后不会再问」。卡片最底部一行灰字「拉回来的录音来源标成「飞书」，飞书的文字稿和总结也一起存下来对照。」整体克制。$S"
