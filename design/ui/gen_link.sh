#!/bin/zsh
# 让 Codex 出「从链接导入」的设计图：粘贴窗口，和导入后在列表、详情里的样子。
cd "$(dirname "$0")"
gen() {
  local name=$1; local prompt=$2
  [ -f "$name.png" ] && return
  local t0=$(date +%s)
  codex exec --skip-git-repo-check --ephemeral -c 'model_reasoning_effort="low"' -C "$PWD" -s workspace-write \
    "当前目录有 ui_list_rows.png，是这款产品 Mac 版已经定稿的录音页。请先看这张图，然后使用内置的 image_gen 工具（把它一起传入，保持风格完全一致）生成一张 16:10 横向的高保真 UI 设计稿（正视图、不要透视）：$prompt 生成后把最终图片复制到当前目录，命名为 $name.png，然后只回复文件名。" < /dev/null > "$name.log" 2>&1
  echo "$name $(( $(date +%s) - t0 ))s $([ -f $name.png ] && echo ok || echo FAIL)"
}
S="产品是 macOS 应用「豆仓」：把录音转成文字、整理成纪要，并能改写成口播稿。现在要加一个新入口：粘贴一条别人的视频链接（抖音、B 站、YouTube 等），豆仓把它下载下来、转成文字稿、整理，和自己的录音放在一起。设计语言和参考图一致：暖白纸色背景（#F6F3EC）、石墨黑文字、唯一强调色琥珀橙（#F2A33A）、红色只用于录音按钮；绝对不要蓝色、紫色。文字全部是简体中文，像苹方，清晰可读、没有乱码。"
gen ui_link_import "画面是豆仓的录音页（和参考图同样的三栏布局，背景略微压暗），正中浮着一张 macOS 样式的表单窗口（圆角 16、暖白底、细腻阴影，宽约窗口的 45%）：标题「从链接导入」，下面一行小灰字「粘贴视频链接或整段分享口令，可以一次贴好几条。」；中间是一个大的多行输入框，里面已经贴了两行内容：一行是「7.43 复制打开抖音，看看【某某的作品】… https://v.douyin.com/iABcd12/」，一行是「https://www.bilibili.com/video/BV1xx411c7mD」；输入框下面列出认出来的两条，每条一行：左边一个琥珀色小圆角方块图标（播放三角），然后是平台名「抖音」「B 站」和灰色的短链接，行尾一个绿色小勾；再下面一行小灰字「只导入你有权保存的公开内容。下载下来的只有声音，用来转成文字。」；底部右侧两个按钮：次要的「取消」和琥珀色主按钮「导入 2 条」。窗口顶部正中（表单上方）还有一条小的胶囊形进度提示：琥珀色下载图标、「正在下载「三分钟讲清楚复利」 43%」和一小段进度条。背景里的录音列表第一行是一条已经导入好的内容：左边图标方块是一个播放三角，标题「三分钟讲清楚复利」，下面小信息是「14:20 · 3:12 · 抖音 · @某某」加两个琥珀色小胶囊关键词。$S"
