#!/bin/zsh
# 得到 AI 录音卡：设备页里和录音豆并列的一块，列出卡里的录音、下载、删除。
cd "$(dirname "$0")"
gen() {
  local name=$1; local prompt=$2
  [ -f "$name.png" ] && return
  local t0=$(date +%s)
  codex exec --skip-git-repo-check --ephemeral -c 'model_reasoning_effort="low"' -C "$PWD" -s workspace-write \
    "请使用内置的 image_gen 工具生成一张高保真 UI 设计稿（像设计师在 Figma 里做的最终稿截图，正视图、不要透视、纯浅灰背景上只放这一个窗口）：$prompt 生成后把最终图片复制到当前目录，命名为 $name.png，然后只回复文件名。" < /dev/null > "$name.log" 2>&1
  echo "$name $(( $(date +%s) - t0 ))s $([ -f $name.png ] && echo ok || echo FAIL)"
}
S="这是 macOS 桌面应用「豆仓」（把录音转成文字、整理成纪要）。深色模式。设计语言：苹果 macOS 最新系统的风格加乔纳森·艾维式的克制——圆角卡片、细分隔线、说明是小号灰字、对齐严谨、留白舒服。配色严格限定：深暖灰背景（#1C1917 一类）、卡片比背景略亮的暖灰、浅暖灰文字、唯一强调色玫瑰红（#F43F5E，用在主按钮、进度条、选中状态）；绝对不要蓝色、紫色、青色、彩虹色。界面文字全部是简体中文，字体像苹方，清晰可读、没有乱码。"
gen ui_card_device "【设备页里的「得到录音卡」卡片】一个 macOS 窗口宽约 1180，左边是窄侧栏（小仓鼠头像「豆仓」、开始录音按钮、总览/录音/素材/知识库，底部一张设备小卡「Get-A78A67 · 已连接」和一个齿轮设置方块按钮），右边设备页：最上面一张较小的灰色卡片写着「录音豆 · 未连接」和一个「开始搜索」按钮；下面一张主卡片标题「得到录音卡」，左侧一个简洁的卡片形状图标（扁平的名片大小录音卡，暖灰色，不要任何品牌 Logo），标题旁绿色小圆点「已连接 · Get-A78A67」，右上角两个次要按钮「刷新」「断开」；下面一行三个小数据：「电量 82%」「剩余空间 58.3 GB」「卡里 6 条 · 4 条没下载」；再下面是录音列表，每行：日期时间「11月16日 09:12」、灰色小字「约 23 分钟 · 6.1 MB」、右侧状态——已下载的行显示灰色「已在录音库」，正在下载的行显示一条细玫瑰红进度条和「42%」，没下载的行显示一个小按钮「下载」，每行最右边一个「⋯」；列表底部右侧一个玫瑰红主按钮「全部下载（4 条）」；卡片最底部一行小灰字「录音卡不能远程开始录音，在卡上按键录，录完连上就会同步过来。从卡上删除不能恢复。」$S"
wait
