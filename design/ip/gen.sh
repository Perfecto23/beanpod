#!/bin/zsh
# 豆仓 IP 形象概念图：四个方向各出一张，选定后再出多视图去建模。
cd "$(dirname "$0")"
gen() {
  local name=$1; local prompt=$2
  [ -f "$name.png" ] && return
  local t0=$(date +%s)
  codex exec --skip-git-repo-check --ephemeral -c 'model_reasoning_effort="low"' -C "$PWD" -s workspace-write \
    "使用内置的 image_gen 工具生成一张方形图片：$prompt 生成后把最终图片复制到当前目录，命名为 $name.png，然后只回复文件名。" < /dev/null > "$name.log" 2>&1
  echo "$name $(( $(date +%s) - t0 ))s $([ -f $name.png ] && echo ok || echo FAIL)"
}
C="高品质 3D 角色设计渲染，像高端潮玩手办的质感，柔和棚拍光，正面略偏三分之四角度，全身完整入画居中，站立的自然姿势，纯净的浅灰白背景，脚下只有淡淡的接触阴影。造型简洁、轮廓清晰，缩成很小的图标也认得出来。配色克制，以珍珠白为主，只用一种点缀色。无文字、无 Logo、无水印。原创角色，不像任何已有动画或品牌角色。"
gen a_hamster "一个叫「豆仓」的 AI 录音助手吉祥物，方向是「仓鼠」：一只圆滚滚的小仓鼠，珍珠白的短绒毛，两边腮帮子鼓鼓的，里面像是塞满了东西（它把听到的话像存粮食一样存进腮帮），圆圆的小耳朵，黑亮的豆豆眼，神情专注又乖巧，脖子上挂着一副小巧的白色头戴耳机，一只小爪子里捧着一颗发着柔和蓝光的小豆子。点缀色是清澈的天蓝色。$C" &
gen b_beanbot "一个叫「豆仓」的 AI 录音助手吉祥物，方向是「豆子机器人」：身体是一颗圆润饱满的豆子形状（像一颗立起来的蚕豆或胶囊），珍珠白的光滑陶瓷质感外壳，脸部是一块深色的弧形玻璃面罩，面罩上有两只简单的发光眼睛，头顶侧面有一个小小的金属夹子像发卡一样（呼应可以夹在衣领上的录音豆），肚子上有一道细细的圆弧开口像小仓门，门缝里透出柔和的蓝光，短短的圆手圆脚。点缀色是清澈的天蓝色。$C" &
