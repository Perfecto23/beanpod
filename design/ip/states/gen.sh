#!/bin/zsh
# 豆仓的充电仓，以及不同电量下的状态表情。都以正面设定图为参考，保证是同一只仓鼠。
cd "$(dirname "$0")"
gen() {
  local name=$1; local prompt=$2
  [ -f "$name.png" ] && return
  local t0=$(date +%s)
  codex exec --skip-git-repo-check --ephemeral -c 'model_reasoning_effort="low"' -C "$PWD" -s workspace-write \
    "使用内置的 image_gen 工具生成一张方形图片：$prompt 生成后把最终图片复制到当前目录，命名为 $name.png，然后只回复文件名。" -i front.png < /dev/null > "$name.log" 2>&1
  echo "$name $(( $(date +%s) - t0 ))s $([ -f $name.png ] && echo ok || echo FAIL)"
}
R="参考图 front.png 是角色「豆仓」的设定图：一只圆滚滚的珍珠白小仓鼠，鼓腮帮、粉色耳朵内侧、黑亮豆豆眼、脖子上挂着带天蓝色细线的白色耳机。画同一只仓鼠，特征、比例、配色保持一致。高级植绒潮玩手办质感，柔和棚拍光，纯白背景，只有淡淡的接触阴影，无文字无水印。"
CASE="它的充电仓是一个圆润的珍珠白小窝，像一只放大的无线耳机充电盒：下半部分是一个浅浅的圆角碗状底座，里面铺着柔软的浅灰色绒垫，后面连着一片向后掀开的圆弧形盖子，底座正面有一条细细的弧形指示灯带。"
gen case "只画充电仓本身，不要画仓鼠。$CASE 指示灯带亮着柔和的天蓝色。正面略偏三分之四的俯视角度，完整入画居中。高级潮玩手办质感，柔和棚拍光，纯白背景，只有淡淡的接触阴影，无文字无水印。" &
gen charging "$R 状态是「正在充电」：仓鼠蜷成一团窝在充电仓里睡觉，眼睛闭成两道弯弯的弧线，脸颊微红，耳机还挂在脖子上，表情安稳满足。$CASE 指示灯带亮着柔和的天蓝色，像呼吸灯一样有一圈光晕。" &
gen low "$R 状态是「电量很低」：仓鼠坐在地上，累得眼皮耷拉成半睁的样子，耳朵往两边垂下来，身体有点瘫软，一只小手揉着眼睛在打哈欠，头顶冒出一个小小的橙红色低电量标志（一节快空的电池图形）。整体可爱不可怜。" &
gen mid "$R 状态是「电量一半」：仓鼠站着，表情平静专注，眼睛正常睁开，一只手扶着耳机的一侧像在认真听，头顶有一个小小的天蓝色电池图形显示半格电。" &
gen full "$R 状态是「满电」：仓鼠精神十足地踮起脚、双手举高欢呼，眼睛亮晶晶的带星星高光，嘴巴张开大笑，头顶有一个小小的天蓝色满格电池图形，周围有两三颗小小的闪光。" &
wait
