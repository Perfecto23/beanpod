#!/bin/zsh
# 让 Codex 画小豆的各个状态，抠图后放进 App，替换原来的 3D 模型。
cd "$(dirname "$0")"
gen() {
  local name=$1; local prompt=$2
  [ -f "$name.png" ] && return
  codex exec --skip-git-repo-check --ephemeral -c 'model_reasoning_effort="low"' -C "$PWD" -s workspace-write \
    "当前目录有两张参考图 ref_a.png 和 ref_b.png，里面是同一个角色「小豆」：一只珍珠白、毛茸茸、圆滚滚的小仓鼠，腮帮鼓鼓，粉色圆耳朵内侧，黑亮的豆豆眼，粉色小鼻子，一副白色头戴耳机，耳机外圈有琥珀色发光灯环。请先看参考图，然后使用内置的 image_gen 工具（把参考图一起传入，角色长相、毛发质感、比例必须和参考图完全一致）生成一张 1024×1024 的方形图片：$prompt 画面要求：高品质 3D 渲染，高端毛绒潮玩质感，柔和的棚拍光；角色全身完整入画、居中、四周留出一圈空白，脚下不要地面和阴影；背景是完全纯色、均匀的中性暖灰色（#B9B2A6），没有渐变、没有光晕、没有任何其他物体和文字。全画面只有珍珠白、琥珀橙和粉色，不要蓝色紫色。生成后把最终图片复制到当前目录，命名为 $name.png，然后只回复文件名。" < /dev/null > "$name.log" 2>&1
  echo "$name $([ -f $name.png ] && echo ok || echo FAIL)"
}
gen idle "小豆正面站立，耳机挂在脖子上，两只小爪子自然放在身前，表情平静友好，微微带笑。" &
gen listening "小豆把耳机戴在头上罩住耳朵，身体微微前倾，一只小爪子按着一侧耳罩，歪着头专注地听，眼睛明亮。耳机灯环是偏红的琥珀色，正在发光。" &
gen writing "小豆把耳机戴在头上，低着头，一只小爪子握着一支短短的琥珀色铅笔，在抱在怀里的一本小本子上认真写字，神情专注。" &
gen thinking "小豆耳机挂在脖子上，歪着头，一只小爪子托着下巴，眼睛向斜上方看，正在思考，头顶旁边飘着三个小小的琥珀色圆点。" &
gen happy "小豆耳机挂在脖子上，开心地跳起来，两只小爪子高高举起，眼睛笑成弯弯的月牙，身边有两三颗小小的琥珀色星星。" &
gen sleeping "小豆窝在一个打开的白色圆润充电仓里（像无线耳机的充电盒，盖子在身后翻开），闭着眼睛睡着了，耳机挂在脖子上、灯环熄灭不发光，头顶飘着小小的 Zzz。" &
gen charging "小豆坐在一个打开的白色圆润充电仓里（像无线耳机的充电盒，盖子在身后翻开），睁着眼睛、满足地微笑，耳机挂在脖子上、灯环发着琥珀色的光，充电仓正面有一颗亮着的琥珀色小指示灯，身旁飘着一个小小的琥珀色闪电符号。" &
gen low "小豆耳机挂在脖子上，没精神地垂着耳朵和肩膀，眼皮耷拉着很困很累，耳机灯环是暗红色、几乎不亮，身旁有一个小小的红色低电量电池符号。" &
wait
